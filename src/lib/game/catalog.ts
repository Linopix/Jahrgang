function slug(title: string, artist: string, year: number) {
  return `${artist}-${title}-${year}`
    .toLowerCase()
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "");
}

const seen = new Set<string>();

export const CATALOG: CatalogSong[] = ROWS.flatMap(([title, artist, year, german]) => {
  const id = slug(title, artist, year);
  if (seen.has(id)) return [];
  seen.add(id);
  return [{ id, title, artist, year, german: german === 1 }];
});

let titlePool: string[] | null = null;
let artistPool: string[] | null = null;

export function catalogTitles() {
  titlePool ??= [...new Set(CATALOG.map((song) => song.title))];
  return titlePool;
}

export function catalogArtists() {
  artistPool ??= [...new Set(CATALOG.map((song) => song.artist))];
  return artistPool;
}

export function songId(title: string, artist: string, year: number) {
  return slug(title, artist, year);
}

export function matchCatalogSong(title: string, artist: string): CatalogSong | undefined {
  return CATALOG.find(
    (song) =>
      guessMatches(title, song.title, "title") &&
      guessMatches(artist, song.artist, "artist"),
  );
}

export function songsForEra(era: EraId): CatalogSong[] {
  return CATALOG.filter((song) => {
    if (era === "all" || era === "playlist" || era === "mix") return true;
    if (era === "german") return Boolean(song.german);
    if (era === "classic") return song.year <= 1979;
    if (era === "eighties") return song.year >= 1980 && song.year <= 1989;
    if (era === "nineties") return song.year >= 1990 && song.year <= 1999;
    if (era === "two-thousands") return song.year >= 2000 && song.year <= 2009;
    if (era === "tens") return song.year >= 2010 && song.year <= 2019;
    if (era === "today") return song.year >= 2020;
    return true;
  });
}
