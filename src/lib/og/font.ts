export function textWidth(text: string, scale: number, tracking = 1) {
  const gap = scale + tracking * scale;
  return Math.max(0, text.length * (5 * scale + gap) - gap);
}

export function drawText(
  c: Canvas,
  text: string,
  x: number,
  y: number,
  scale: number,
  color: number[],
  tracking = 1,
) {
  let ox = x;
  const gap = scale + tracking * scale;
  for (const ch of text.toUpperCase()) {
    const glyph = GLYPHS[ch] ?? GLYPHS[" "];
    for (let row = 0; row < 7; row++) {
      const bits = glyph[row] ?? 0;
      for (let col = 0; col < 5; col++) {
        if (bits & (1 << (4 - col))) {
          c.fillRect(ox + col * scale, y + row * scale, scale, scale, color);
        }
      }
    }
    ox += 5 * scale + gap;
  }
}
